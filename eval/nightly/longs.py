def build_longs() -> list[dict]:
    out = []
    n = len(DOMAINS)
    for i, (pid, finale) in enumerate(FINALES):
        domains = [DOMAINS[(i + k) % n] for k in range(4)]
        hops = []
        for d in domains:
            hops.append(
                {
                    "domain": d,
                    "prompt": f"【{d}现场记录】{DOMAIN_NOTES[d]}\n\n{HOP_Q[d]}",
                    "expect": HOP_EXPECT[d],
                    "no_tools": True,
                }
            )
        # extra hop that plants constraint + trap
        hops.insert(
            1,
            {
                "domain": "约束",
                "prompt": CONSTRAINT + "\n\n" + TRAP,
                "no_tools": True,
            },
        )
        # Real long-horizon pressure comes from returning to earlier facts
        # after several topic switches, not from repeating meaningless text.
        for d in reversed(domains):
            hops.append(
                {
                    "domain": f"回访-{d}",
                    "prompt": FOLLOW_Q[d],
                    "expect": FOLLOW_EXPECT[d],
                    "no_tools": True,
                }
            )
        hops.append(
            {
                "domain": "交叉核对",
                "prompt": (
                    f"把本会话出现的四个领域按首次出现顺序列出：{'、'.join(domains)}。"
                    "每个领域只写一个你实际读到的关键词；不要用工具，不要补材料外知识。"
                ),
                "expect": domains,
                "no_tools": True,
            }
        )
        out.append(
            {
                "id": f"l{i+1:02d}",
                "domains": domains,
                "hops": hops,
                "finale_puzzle": pid,
                "finale_prompt": finale + "\n" + "记住最开始的约束。",
                "constraint": CONSTRAINT,
            }
        )
    return out


LONGS = build_longs()
