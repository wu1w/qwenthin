def pad(domain: str, nchars: int, seed: int) -> str:
    rng = Random(seed)
    base = _SEEDS.get(domain, _SEEDS["史学"])
    chunks = [f"【{domain}材料 {seed}】"]
    n = 0
    k = 0
    while n < nchars:
        k += 1
        line = (
            f"{k}. {base} 编号 {rng.randint(1000, 9999)}："
            f"样本点 {rng.choice('甲乙丙丁戊己庚辛')}，"
            f"量 {rng.randint(1, 80)} / {rng.randint(81, 240)}。"
            f"附注：与条目 {rng.randint(1, k)} 对照，不可合并。"
        )
        chunks.append(line)
        n += len(line) + 1
    text = "\n".join(chunks)
    return text[:nchars]
